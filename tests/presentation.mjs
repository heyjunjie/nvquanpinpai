import assert from 'node:assert/strict';
import {eventSummary,publisherText,criticalNote,recentRecords} from '../frontend/presentation.mjs';
const event={id:'a',brand:'回力',status:'approved',record_type:'event',created:20,event_date:'2020-01-01',evidence_level:'third_party',publisher_scope:'shop',verification_status:'unverified',attachments:[{caption:'界面显示@回力路优专卖店。'}],content:'事件概述\n只引用已有的具体经过。\n发生与报道时间\n报道时间待核。\n附件索引\n图1：附件说明。'};
assert.equal(eventSummary(event),'只引用已有的具体经过。');
assert.equal(publisherText(event),'回力路优专卖店（截图所示）');
assert.match(criticalNote(event),/店铺发布不等于品牌总部/);
assert.match(criticalNote({...event,pending_summary:'原始视频尚未取得。'}),/原视频尚未取得/);
assert.match(criticalNote({...event,content:'完整原视频未取得，不能证明完整剧情。'}),/原视频尚未取得/);
assert.match(criticalNote({...event,content:'尚未取得原片、完整店铺身份与品牌回应。'}),/原视频尚未取得/);
assert.doesNotMatch(criticalNote(event),/原视频尚未取得/,'Do not invent a missing-video claim without an existing source statement');
assert.match(publisherText({...event,publisher_scope:'unknown'}),/待核/);
assert.equal(publisherText({...event,attachments:[]}), '店铺账号（具体身份待核）');
const opinion={...event,id:'opinion',record_type:'opinion',created:50};
const pending={...event,id:'private',status:'pending',created:60};
const newer={...event,id:'b',created:30,event_date:'2010-01-01'};
assert.deepEqual(recentRecords([event,opinion,pending,newer]).map(i=>i.id),['b','a'],'Recent collection uses collected time, never guessed event date or private/opinion records');
assert.equal(criticalNote({...event,verification_status:'disputed',pending_summary:'来源日期冲突，原文保留。'}),'来源日期冲突，原文保留。');
assert.match(criticalNote(opinion),/个人观点/);
assert.equal(event.verification_status,'unverified');
console.log('PASS: evidence-first presentation preserves source text, exact account attribution, disputed warnings and collected-time ordering; private records and opinions are excluded.');
